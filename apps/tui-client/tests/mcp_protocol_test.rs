    let mock = MockServer::start().await;
    let expected_sid = "mcp_test_session_id_0123456789abcdef";

    // Session register → strict body matcher.
    //
    // Codex round 21 (MED): the register payload is the *only* place
    // the TUI MCP runtime announces (protocol_version, client_name,
    // product_phase, local_secret_generation) to the control plane.
    // The lsg value is dynamic (generated by the runtime), so we match
    // the three static fields with `body_partial_json` and re-check the
    // entire payload (including a non-empty `local_secret_generation`)
    // via `received_requests()` in phase 4 once the runtime is up.
    Mock::given(method("POST"))
        .and(path("/api/mcp/session/register"))
        .and(header("Authorization", "Bearer fake-jwt-for-tui-test"))
        .and(body_partial_json(json!({
            "protocol_version": "2025-06-18",
            "client_name": "canopy-local-mcp",
            "product_phase": "phase_3_data_tools"
        })))
        .respond_with(ResponseTemplate::new(200).set_body_json(json!({
            "canopy_mcp_session_id": expected_sid,
            "forwarding_key": "fk-test-0123456789abcdefghijklmnopqrstuvwxyz",
            "expires_at": "2099-01-01T00:00:00Z"
        })))
        .mount(&mock)
        .await;

    // ── Phase 2: build ApiClient + entitlements + runtime ──────────────
    //
    // We mount the upstream-forwarding mocks (guidance/scopes/query)
    // *after* `McpRuntime::start` returns because we need the
    // runtime-generated `local_secret_generation` value to plumb into
    // their `body_partial_json` matchers. Without that, the matchers
    // would only assert that sid/scope/sql appear — the same hole
    // round 21 flagged.
    let api = ApiClient::new(&mock.uri()).expect("ApiClient::new");
    api.set_token("fake-jwt-for-tui-test".into());

    // Redirect ~/.canopy to a tempdir so the test cannot poison the
    // developer's real session file.
    let tmp_home = tempfile::tempdir().expect("home tempdir");
    let _home_guard = HomeGuard::set(tmp_home.path());

    let runtime = McpRuntime::start(api, dev_admin_entitlements())
        .await
        .expect("McpRuntime::start");
    let expected_lsg = runtime.local_secret_generation().to_string();
    assert!(
        expected_lsg.starts_with("lsg_"),
        "runtime local_secret_generation should look like 'lsg_<uuid>': {expected_lsg}"
    );

    // Codex round 20+21 (MED): every upstream mock requires the bearer
    // header AND a JSON body containing the session id, the
    // runtime-generated local_secret_generation, plus the request-
    // specific fields (scope, sql, guidance_id, ...). With these
    // strict matchers, a regression that drops the bearer, omits any
    // of these fields, or sends a stale lsg would fail the test
    // instead of silently passing. `body_partial_json` ignores fields
    // the runtime adds for its own bookkeeping while still asserting
    // the load-bearing ones.
    //
    // Guidance sync — assert (sid, lsg, guidance_id, guidance_version)
    // make it through. `.expect(1)` makes a missing `canopy_get_guidance`
    // tool call fail the test instead of leaving the mock unused.
    Mock::given(method("POST"))
        .and(path("/api/mcp/guidance/delivered"))
        .and(header("Authorization", "Bearer fake-jwt-for-tui-test"))
        .and(body_partial_json(json!({
            "canopy_mcp_session_id": expected_sid,
            "local_secret_generation": expected_lsg,
            "guidance_id": "database_query_workflow",
            "guidance_version": "2026-05-13"
        })))
