//! Protocol-compliance test for the in-TUI MCP HTTP server. Spins up:
//!
//!   * a `wiremock::MockServer` standing in for the control-plane
//!   * a real `tui_client::mcp::McpRuntime` pointed at that mock
//!
//! and drives JSON-RPC over real TCP against the runtime's loopback
//! endpoint, the same way Claude CLI / Codex CLI do in production. The
//! goal is to catch protocol regressions (initialize → Mcp-Session-Id
//! handshake, tools/list shape, tool-call forwarding to control-plane,
//! auth gating, origin gating) without needing a real control-plane
//! binary OR a real AI client.
//!
//! Single-test design: the runtime writes its session file to
//! `$HOME/.canopy/mcp-session.json`, which is process-global state. We
//! override `HOME` to a tempdir at the start of the test. Cargo's
//! default per-binary test parallelism means this binary's HOME
//! mutation is isolated from other test crates.

